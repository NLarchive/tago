"""Generate docs/results_v38.md from the committed run artifacts. `--check` fails when the file is stale."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tago.workflows.analysis import run_summary, markdown_report, markdown_synthetic

RUNS = [('A', 'v3.7', 'v37_colab_t4_qwen2.5-7b'), ('B', 'v3.8.1', 'v38_1_colab_t4_qwen2.5-7b'), ('C', 'v3.8.2', 'v38_2_colab_t4_qwen2.5-7b'),
        ('D', 'v3.8.3', 'v38_3_colab_t4_qwen2.5-7b'), ('E', 'v3.8.4', 'v38_4_colab_t4_qwen2.5-7b'), ('F (repeat)', 'v3.8.4', 'v38_4_repeat_colab_t4_qwen2.5-7b')]

def build():
    out = ['# TAGO v3.8 results', '', 'Generated by `python tools/build_report.py` from the artifacts under `results/`; do not edit by hand.',
           'All runs: Colab T4, Ollama 0.40.18, `qwen2.5:7b`, seed 3800, golden cases E01, E03 and E06.', '', '## Golden cases by run', '']
    out.append(markdown_report([run_summary(ROOT / 'results' / d) for _, _, d in RUNS]))
    for label, version, d in RUNS:
        path = ROOT / 'results' / d
        if (path / 'synthetic' / 'summary.json').exists():
            out += ['', f'## Synthetic sweep, Run {label} ({version})', '', markdown_synthetic(path)]
    out += ['', '## Experiment campaign (Run F)', '', (ROOT / 'results' / 'v38_4_campaign_colab_t4' / 'campaign_report.md').read_text(encoding='utf-8').rstrip(),
            '', 'Three golden cases per row cannot rank models; see `docs/v38_review.md`, section 10, for the reading.']
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    target = ROOT / 'docs' / 'results_v38.md'
    text = build()
    if '--check' in sys.argv:
        if not target.exists() or target.read_text(encoding='utf-8') != text: print('docs/results_v38.md is stale: run python tools/build_report.py'); sys.exit(1)
        print('Report is in sync with the artifacts.'); sys.exit(0)
    target.write_text(text, encoding='utf-8'); print('Wrote', target.relative_to(ROOT))
